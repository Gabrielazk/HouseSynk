# Espaço que não quebra a linha: o Kivy só quebra a linha no espaço comum (" ").
ESPACO_FIXO = "\u00a0"
_NUMERO_E_PALAVRA = re.compile(r"(\d) (?=[^\s\d=(•·+\-])")  # "12 m", "788 un", "3 latas"
_MOEDA_E_NUMERO = re.compile(r"(\$) (?=\d)")                 # "R$ 54,00", "US$ 4,902.70"
_NUMERO_E_FRACAO = re.compile(r"(\d) (?=\d+/\d)")            # "11 3/4" (EUA)
_X_ENTRE_NUMEROS = re.compile(r"(\d)[ \u00a0]x (?=\d)")     # "11 3/4 x 12 in" (peça nos EUA)
_NOMES_JUNTOS = ("ANSI A118",)                              # "(ANSI A118.4)" não quebra no meio


def sem_quebra(texto: str) -> str:
    """Texto para MOSTRAR na tela, sem separar o número da unidade na quebra de linha
    (antes saía "12" no fim de uma linha e "m" no começo da outra). Troca o espaço entre o número
    e a palavra seguinte (e entre o R$ e o valor) por um espaço que não quebra.
    Só para a tela: o texto guardado (Histórico, PDF, WhatsApp) continua com o espaço comum."""
    texto = _NUMERO_E_PALAVRA.sub(rf"\1{ESPACO_FIXO}", texto)
    # Medidas dos EUA inteiras na mesma linha: "11 3/4" e "11 3/4 x 12 in" (rodada 3, P7)
    texto = _NUMERO_E_FRACAO.sub(rf"\1{ESPACO_FIXO}", texto)
    texto = _X_ENTRE_NUMEROS.sub(rf"\1{ESPACO_FIXO}x{ESPACO_FIXO}", texto)
    # Nomes que não podem ser cortados no meio (rodada 3, P10)
    for nome in _NOMES_JUNTOS:
        texto = texto.replace(nome, nome.replace(" ", ESPACO_FIXO))
    return _MOEDA_E_NUMERO.sub(rf"\1{ESPACO_FIXO}", texto)


def fmt_moeda(valor: float) -> str:
    """Ex.: R$ 4.902,70 (Brasil) ou US$ 4,902.70 (EUA): o separador de milhar é o contrário do decimal."""
    sep = CONFIG_APP["separador_decimal"]
    milhar = "." if sep == "," else ","
    moeda = CONFIG_APP["moeda"]
    texto = f"{valor:,.2f}"  # 4,902.70 (padrão do Python)
    texto = texto.replace(",", "#").replace(".", sep).replace("#", milhar)
    return f"{moeda} {texto}"

def fmt_num(valor: float, casas: int = 2) -> str:
    """Número com as casas pedidas e separador de milhar: 2363 -> "2.363", 100000 -> "100.000,00"
    (Brasil) ou "100,000.00" (EUA). Arredonda do jeito da escola (1,575 -> 1,58): ver arredondar(),
    no unidades.py, que explica por que o round() do Python não serve."""
    sep = CONFIG_APP["separador_decimal"]
    milhar = "." if sep == "," else ","
    texto = f"{arredondar(valor, casas):,.{casas}f}"  # 100,000.00 (padrão do Python)
    return texto.replace(",", "#").replace(".", sep).replace("#", milhar)

def fmt_int(valor) -> str:
    """Quantidade inteira (sacos, peças, unidades) com separador de milhar: 2363 -> "2.363"."""
    return fmt_num(valor, 0)